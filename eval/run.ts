/**
 * Runs the recall scenarios and reports how many pass in each category.
 *
 *   npm run eval
 *
 * No model and no network are involved, so the numbers are exact. The report
 * is printed and written to eval/recall-results.md.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { recall, renderContext } from "../src/memory/recall.ts";
import { MemoryStore } from "../src/memory/store.ts";
import { HISTORY, NOW, SCENARIOS, TIMEZONE, type Scenario } from "./recall-scenarios.ts";

interface Outcome {
  scenario: Scenario;
  passed: boolean;
  problems: string[];
  ms: number;
}

function run(scenario: Scenario): Outcome {
  const store = new MemoryStore(":memory:");
  for (const turn of scenario.history ?? HISTORY) {
    store.createConversation({ id: turn.conversationId, title: turn.question, createdAt: turn.createdAt, updatedAt: turn.createdAt });
    store.saveTurn(turn);
  }
  const input = {
    message: scenario.message,
    nowMs: Date.parse(scenario.now ?? NOW),
    timezone: scenario.timezone ?? TIMEZONE,
    inContext: new Set<string>(),
  };
  const started = performance.now();
  const result = recall(store, input);
  const context = renderContext(result, input);
  const ms = performance.now() - started;
  store.close();

  const problems: string[] = [];
  if (scenario.recalled) {
    const got = result.hits.map((hit) => hit.turn.id).sort();
    const want = [...scenario.recalled].sort();
    if (got.join() !== want.join()) problems.push(`recalled [${got.join(", ")}], expected [${want.join(", ")}]`);
  }
  for (const pattern of scenario.context ?? []) if (!pattern.test(context)) problems.push(`context lacks ${pattern}`);
  for (const pattern of scenario.notContext ?? []) if (pattern.test(context)) problems.push(`context should not contain ${pattern}`);
  return { scenario, passed: problems.length === 0, problems, ms };
}

const outcomes = SCENARIOS.map(run);
const categories = [...new Set(SCENARIOS.map((s) => s.category))];
const passed = outcomes.filter((o) => o.passed).length;
const meanMs = outcomes.reduce((sum, o) => sum + o.ms, 0) / outcomes.length;

const lines = [
  "# Recall evaluation",
  "",
  "Generated by `npm run eval`. These scenarios test date reading and memory lookup, which run in code with no model, so the results are exact and repeatable.",
  "",
  "| Category | Passed |",
  "|---|---|",
  ...categories.map((category) => {
    const inCategory = outcomes.filter((o) => o.scenario.category === category);
    return `| ${category} | ${inCategory.filter((o) => o.passed).length} / ${inCategory.length} |`;
  }),
  `| **Total** | **${passed} / ${outcomes.length}** |`,
  "",
  `Mean lookup time: ${meanMs.toFixed(2)} ms per message.`,
  "",
];
const failures = outcomes.filter((o) => !o.passed);
if (failures.length > 0) {
  lines.push("## Failures", "");
  for (const failure of failures) {
    lines.push(`- **${failure.scenario.category}: ${failure.scenario.name}**. "${failure.scenario.message}": ${failure.problems.join("; ")}`);
  }
  lines.push("");
}

const report = lines.join("\n");
console.log(report);
writeFileSync(fileURLToPath(new URL("recall-results.md", import.meta.url)), report);
